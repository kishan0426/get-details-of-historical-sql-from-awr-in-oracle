PROMPT TIME_FORMAT(DD-MON-YYYY HH24:MI:SS)
DEFINE SQL_TEXT_SEARCH = '&SQL_TEXT';
DEFINE START_TIME = '&STARTTIME';
DEFINE END_TIME   = '&ENDTIME';

WITH SQL_DETAILS AS
(
    SELECT
        S.DBID,
        S.INSTANCE_NUMBER,
        S.SQL_ID,
        S.PLAN_HASH_VALUE,
        S.SNAP_ID,
        S.EXECUTIONS_DELTA,
        S.ELAPSED_TIME_DELTA,
        S.CPU_TIME_DELTA,
        S.BUFFER_GETS_DELTA,
        S.DISK_READS_DELTA,
        S.ROWS_PROCESSED_DELTA,
        S.PARSE_CALLS_DELTA,
        S.LOADS_DELTA,
        S.INVALIDATIONS_DELTA,
        S.IOWAIT_DELTA,
        S.CLWAIT_DELTA,
        S.APWAIT_DELTA,
        S.CCWAIT_DELTA,
        S.PX_SERVERS_EXECS_DELTA,
        T.SQL_TEXT
    FROM DBA_HIST_SQLSTAT S
    JOIN DBA_HIST_SQLTEXT T
        ON T.DBID = S.DBID
       AND T.SQL_ID = S.SQL_ID
    WHERE UPPER(T.SQL_TEXT)
          LIKE UPPER('%&SQL_TEXT_SEARCH%')
),
ASH_DETAILS AS
(
    SELECT
        A.DBID,
        A.INSTANCE_NUMBER,
        A.SAMPLE_TIME,
        A.SESSION_ID,
        A.SESSION_SERIAL#,
        A.SQL_ID,
        A.SQL_PLAN_HASH_VALUE,
        A.SESSION_STATE,
        A.EVENT,
        A.WAIT_CLASS,
        A.TIME_WAITED,
        A.BLOCKING_SESSION_STATUS,
        A.BLOCKING_INST_ID,
        A.BLOCKING_SESSION,
        A.BLOCKING_SESSION_SERIAL#,
        A.SQL_EXEC_ID,
        A.SQL_EXEC_START
    FROM DBA_HIST_ACTIVE_SESS_HISTORY A
    WHERE A.SAMPLE_TIME BETWEEN
          TO_TIMESTAMP('&START_TIME','DD-MON-YYYY HH24:MI:SS')
          AND
          TO_TIMESTAMP('&END_TIME','DD-MON-YYYY HH24:MI:SS')
)
SELECT
    SD.SQL_ID,
    SD.SQL_TEXT,
    SD.INSTANCE_NUMBER,
    SD.SNAP_ID,
    SN.BEGIN_INTERVAL_TIME,
    SN.END_INTERVAL_TIME,
    SD.PLAN_HASH_VALUE,
    SD.EXECUTIONS_DELTA AS EXECUTIONS,
    ROUND(SD.ELAPSED_TIME_DELTA / 1000000, 2)
        AS ELAPSED_SEC,
    ROUND(SD.CPU_TIME_DELTA / 1000000, 2)
        AS CPU_SEC,
    ROUND(
        SD.ELAPSED_TIME_DELTA /
        NULLIF(SD.EXECUTIONS_DELTA, 0) / 1000000, 4
    ) AS AVG_ELAPSED_SEC_PER_EXEC,
    ROUND(
        SD.CPU_TIME_DELTA /
        NULLIF(SD.EXECUTIONS_DELTA, 0) / 1000000, 4
    ) AS AVG_CPU_SEC_PER_EXEC,
    SD.BUFFER_GETS_DELTA AS BUFFER_GETS,
    SD.DISK_READS_DELTA AS DISK_READS,
    SD.ROWS_PROCESSED_DELTA AS ROWS_PROCESSED,
    SD.PARSE_CALLS_DELTA AS PARSE_CALLS,
    SD.LOADS_DELTA AS LOADS,
    SD.INVALIDATIONS_DELTA AS INVALIDATIONS,
    ROUND(SD.IOWAIT_DELTA / 1000000, 2) AS IO_WAIT_SEC,
    ROUND(SD.CLWAIT_DELTA / 1000000, 2) AS CL_WAIT_SEC,
    ROUND(SD.APWAIT_DELTA / 1000000, 2) AS AP_WAIT_SEC,
    ROUND(SD.CCWAIT_DELTA / 1000000, 2) AS CC_WAIT_SEC,
    SD.PX_SERVERS_EXECS_DELTA,
    AH.SAMPLE_TIME,
    AH.SESSION_ID AS SESSION_ID,
    AH.SESSION_SERIAL# AS SESSION_SERIAL,
    AH.SESSION_STATE,
    AH.EVENT,
    AH.WAIT_CLASS,
    AH.TIME_WAITED,
    AH.BLOCKING_SESSION_STATUS,
    AH.BLOCKING_INST_ID,
    AH.BLOCKING_SESSION,
    AH.BLOCKING_SESSION_SERIAL#,
    AH.SQL_EXEC_ID,
    AH.SQL_EXEC_START
FROM SQL_DETAILS SD
LEFT JOIN DBA_HIST_SNAPSHOT SN
    ON SN.DBID = SD.DBID
   AND SN.INSTANCE_NUMBER = SD.INSTANCE_NUMBER
   AND SN.SNAP_ID = SD.SNAP_ID
LEFT JOIN ASH_DETAILS AH
    ON AH.DBID = SD.DBID
   AND AH.INSTANCE_NUMBER = SD.INSTANCE_NUMBER
   AND AH.SQL_ID = SD.SQL_ID
   AND AH.SAMPLE_TIME >= SN.BEGIN_INTERVAL_TIME
   AND AH.SAMPLE_TIME < SN.END_INTERVAL_TIME
WHERE SN.BEGIN_INTERVAL_TIME >=
      TO_DATE('&START_TIME','DD-MON-YYYY HH24:MI:SS')
  AND SN.END_INTERVAL_TIME <=
      TO_DATE('&END_TIME','DD-MON-YYYY HH24:MI:SS')
ORDER BY
    SN.BEGIN_INTERVAL_TIME DESC,
    SD.ELAPSED_TIME_DELTA DESC,
    AH.SAMPLE_TIME DESC;
